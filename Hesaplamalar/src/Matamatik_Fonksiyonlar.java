public class Matamatik_Fonksiyonlar {
    public int KupAl(int number) {
        int result = number * number * number;
        return result;
    }
    public int  Toplama(int number1, int number2) {
        int result = number1 + number2;
        return result;
    }
    public int  KareAl(int number1) {
        return number1 * number1;
    }
    public double KarekökAl(double number1) {
        return Math.sqrt(number1);
    }
    public double MutlakDegerAl(int number1) {
        return Math.abs(number1);
    }
}
